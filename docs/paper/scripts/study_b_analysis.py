def write_arff(path, rows, feats):
    with open(path, "w", encoding="utf-8") as f:
        f.write("@relation studyB\n")
        for name, kind in FEATURES:
            if name not in feats:
                continue
            if kind == "num":
                f.write("@attribute %s numeric\n" % name)
            elif kind == "bool":
                f.write("@attribute %s {F,T}\n" % name)
            else:
                f.write("@attribute %s {UNLOCK,DENY,NONE,ERROR}\n" % name)
        f.write("@attribute cls {%s}\n@data\n" % ",".join(CLASSES))
        for r in rows:
            vals = []
            for name, kind in FEATURES:
                if name not in feats:
                    continue
                v = r["card_blocked"] if name == "card_blocked" else r[name]
                vals.append(("T" if v else "F") if kind == "bool" else str(v))
            f.write(",".join(vals + [to5(r["gt6"])]) + "\n")


def weka_predict(clf, train, test, workdir, feats, tag):
    tr, te = os.path.join(workdir, tag + "_train.arff"), os.path.join(workdir, tag + "_test.arff")
    write_arff(tr, train, feats)
    write_arff(te, test, feats)
    cmd = [JAVA, "-cp", WEKA, clf, "-t", tr, "-T", te, "-o",
           "-classifications", "weka.classifiers.evaluation.output.prediction.CSV"]
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    preds = []
    for line in out.splitlines():
        parts = line.strip().split(",")
        if len(parts) >= 3 and parts[0].isdigit():
            preds.append(parts[2].split(":", 1)[1])
    assert len(preds) == len(test), (tag, len(preds), len(test))
    return preds


# ----------------------------------------------------------------------------- v2 extras
CONTEXT_ONLY = ["rfid_ok", "auth_result", "card_blocked", "network_latency_ms", "seq_replay"]  # auth/network/credential fields
NUMERIC = ["door_open_sec", "weight_delta_g", "abs_weight", "stay_min", "ultrasonic_dist_cm", "vibration_intensity",
           "tilt_deg", "shock_mag_g", "network_latency_ms", "rfid_ok_n", "card_blocked_n", "seq_replay_n",
           "auth_unlock", "auth_deny", "auth_none"]


def feat_vec(r):
    d = dict(r)
    d.update(abs_weight=abs(r["weight_delta_g"]), rfid_ok_n=float(r["rfid_ok"]), card_blocked_n=float(r["card_blocked"]),
             seq_replay_n=float(r["seq_replay"]), auth_unlock=float(r["auth_result"] == "UNLOCK"),
             auth_deny=float(r["auth_result"] == "DENY"), auth_none=float(r["auth_result"] == "NONE"))
    return d


def stump(vals, pos):
    """Best one-feature threshold (either direction) for class-vs-rest; returns (balanced accuracy, threshold, direction)."""
    n1 = sum(pos); n0 = len(pos) - n1
    best = (0.5, None, None)
    pts = sorted(zip(vals, pos))
    uniq = sorted(set(vals))
    for a, b in zip(uniq, uniq[1:]):
        t = (a + b) / 2
        tp_hi = sum(1 for v, q in pts if v > t and q)
        tn_hi = sum(1 for v, q in pts if v <= t and not q)
        for d, tpr, tnr in (("above", tp_hi / n1, tn_hi / n0), ("below", 1 - tp_hi / n1, 1 - tn_hi / n0)):
            ba = (tpr + tnr) / 2
            if ba > best[0]:
                best = (ba, t, d)
    return best


def quantiles(v):
    v = sorted(v)
    q = lambda f: v[min(len(v) - 1, int(round(f * (len(v) - 1))))]  # nearest rank on the pooled sample
    return {"min": v[0], "p05": q(0.05), "median": q(0.5), "p95": q(0.95), "max": v[-1], "n": len(v)}


def v2_extra(per_seed, outdir, allf, sd):
    pooled = [feat_vec(r) for s in SEEDS for r in per_seed[s]]
    out = {}
    # context-only leakage check: J48 on auth/network/credential fields only, leave-one-seed-out
    per = []
    for s in SEEDS:
        train = [r for t in SEEDS if t != s for r in per_seed[t]]
        pr = weka_predict("weka.classifiers.trees.J48", train, per_seed[s], outdir, CONTEXT_ONLY, "ctx_s%d" % s)
        m = metrics([to5(r["gt6"]) for r in per_seed[s]], pr)
        per.append({"seed": s, "macro_f1": m["macro"]["f1"], "accuracy": m["accuracy"],
                    "recall": {c: m["per_class"][c]["recall"] for c in CLASSES}})
    v = [t["macro_f1"] for t in per]
    out["context_only_J48"] = {"features": CONTEXT_ONLY, "per_seed": per, "mean": sum(v) / len(v), "sd_sample_ddof1": sd(v, 1)}
    # per-class overlap diagnostics on the pooled 500 sessions (5 seeds x 100; descriptive, not inferential)
    y = [to5(r["gt6"]) for r in pooled]
    diag = {"pooled_n": len(pooled), "quantiles": {}, "best_single_feature_stump_one_vs_rest": {}}
    for c in CLASSES:
        diag["quantiles"][c] = {f: quantiles([r[f] for r, a in zip(pooled, y) if a == c])
                                for f in ("door_open_sec", "abs_weight", "ultrasonic_dist_cm", "vibration_intensity",
                                          "tilt_deg", "shock_mag_g", "network_latency_ms", "stay_min")}
        pos = [a == c for a in y]
        res = {f: stump([r[f] for r in pooled], pos) for f in NUMERIC}
        bf = max(res, key=lambda f: res[f][0])
        diag["best_single_feature_stump_one_vs_rest"][c] = {
            "feature": bf, "balanced_accuracy": res[bf][0], "threshold": res[bf][1], "direction": res[bf][2],
            "perfectly_separable_by_one_feature": res[bf][0] == 1.0,
            "all_features": {f: res[f][0] for f in NUMERIC}}
    out["overlap_diagnostics"] = diag
    return out


# ----------------------------------------------------------------------------- main
def main():
    run_id = ("R2_STUDYB_V2_" if VARIANT == "v2" else "R2_STUDYB_") + datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    outdir = os.path.join(ROOT, "docs", "paper", "scripts", "results", run_id)
    os.makedirs(outdir, exist_ok=False)
    res = {"run_id": run_id, "variant": VARIANT}

    # 1. evaluation-path check on the live seed-42 run
    live, checks = live_rows()
    reran = run_detectors(live)
    res["path_check"] = dict(
        checks,
        n=len(live),
        b0_rerun_equals_recorded=sum(1 for r, (a, _) in zip(live, reran) if a == r["rec_b0"]),
        b1_rerun_equals_recorded=sum(1 for r, (_, b) in zip(live, reran) if b == r["rec_b1"]),
        mapping_equals_category=sum(1 for r in live if to5(r["gt6"]) == r["category"]),
    )
    y = [to5(r["gt6"]) for r in live]
    p0 = [to5(r["rec_b0"]) for r in live]
    p1 = [to5(r["rec_b1"]) for r in live]
    res["supports"] = {c: y.count(c) for c in CLASSES}
    res["seed42"] = {"B0": metrics(y, p0), "B1": metrics(y, p1),
                     "mcnemar_binary": mcnemar(y, p0, p1, True),
                     "mcnemar_5class": mcnemar(y, p0, p1, False)}

    # 2. five seeds (seed 42 from the live run; others offline, auth_result = expected outcome)
    per_seed = {42: live}
    for s in SEEDS[1:]:
        per_seed[s] = scenario_rows(s)
    for s, rows in per_seed.items():
        for r in rows:
            r["card_blocked"] = r["credential"] in BLOCKED
    seed_tab = []
    for s in SEEDS:
        rows = per_seed[s]
        lab = [(r["rec_b0"], r["rec_b1"]) for r in rows] if s == 42 else run_detectors(rows)
        ys = [to5(r["gt6"]) for r in rows]
        seed_tab.append({"seed": s, "B0": macro_f1(ys, [to5(a) for a, _ in lab]),
                         "B1": macro_f1(ys, [to5(b) for _, b in lab])})

    def sd(v, ddof):
        m = sum(v) / len(v)
        return math.sqrt(sum((x - m) ** 2 for x in v) / (len(v) - ddof))
    res["five_seed"] = {"per_seed": seed_tab}
    for k in ("B0", "B1"):
        v = [t[k] for t in seed_tab]
        res["five_seed"][k] = {"mean": sum(v) / len(v), "sd_sample_ddof1": sd(v, 1), "sd_population_ddof0": sd(v, 0)}

    # 3. stratified paired bootstrap over the 100 sessions of the seed-42 run
    rng = random.Random(BOOT_SEED)
    idx_by_class = {c: [i for i, a in enumerate(y) if a == c] for c in CLASSES}
    deltas, f0s, f1s = [], [], []
    for _ in range(BOOT_N):
        idx = [rng.choice(ix) for c in CLASSES for ix in [idx_by_class[c]] for _ in ix]
        yy = [y[i] for i in idx]
        a, b = macro_f1(yy, [p0[i] for i in idx]), macro_f1(yy, [p1[i] for i in idx])
        f0s.append(a); f1s.append(b); deltas.append(b - a)

    def pct(v, q):  # linear interpolation between order statistics
        v = sorted(v); h = (len(v) - 1) * q; lo = math.floor(h)
        return v[lo] + (v[min(lo + 1, len(v) - 1)] - v[lo]) * (h - lo)
    res["bootstrap"] = {
        "design": "stratified paired bootstrap; unit = session; same indices for B0 and B1; "
                  "resampled within each of the 5 classes (20 per class)",
        "run": LIVE_RUN, "resamples": BOOT_N, "seed": BOOT_SEED, "percentile_method": "linear interpolation",
        "delta_macro_f1_point": macro_f1(y, p1) - macro_f1(y, p0),
        "delta_ci95": [pct(deltas, 0.025), pct(deltas, 0.975)],
        "B0_ci95": [pct(f0s, 0.025), pct(f0s, 0.975)], "B1_ci95": [pct(f1s, 0.025), pct(f1s, 0.975)],
        "share_delta_le_0": sum(1 for d in deltas if d <= 0) / BOOT_N,
    }

    # 4. learned baselines, leave-one-seed-out (train on the 4 other campaigns, test on the held-out one)
    allf = [n for n, _ in FEATURES]
    learned = {}
    for clf, name in (("weka.classifiers.trees.J48", "J48"), ("weka.classifiers.functions.Logistic", "Logistic")):
        learned[name] = {"per_seed": []}
        for s in SEEDS:
            train = [r for t in SEEDS if t != s for r in per_seed[t]]
            test = per_seed[s]
            pr = weka_predict(clf, train, test, outdir, allf, "%s_s%d" % (name, s))
            ys = [to5(r["gt6"]) for r in test]
            m = metrics(ys, pr)
            learned[name]["per_seed"].append({"seed": s, "macro_f1": m["macro"]["f1"],
                                              "recall": {c: m["per_class"][c]["recall"] for c in CLASSES}})
            if s == 42:
                learned[name]["seed42"] = m
                learned[name]["seed42_preds"] = pr
                learned[name]["mcnemar_binary_vs_B1"] = mcnemar(ys, pr, p1, True)
        v = [t["macro_f1"] for t in learned[name]["per_seed"]]
        learned[name]["mean"] = sum(v) / len(v)
        learned[name]["sd_sample_ddof1"] = sd(v, 1)
    res["learned_baselines"] = learned

    # 5. retrained ablation of the learned J48 baseline (drop one feature group, retrain, same splits)
    abl = {}
    for g, cols in [("none", [])] + list(GROUPS.items()):
        feats = [f for f in allf if f not in cols]
        per = []
        for s in SEEDS:
            train = [r for t in SEEDS if t != s for r in per_seed[t]]
            pr = weka_predict("weka.classifiers.trees.J48", train, per_seed[s], outdir, feats, "abl_%s_s%d" % (g, s))
            m = metrics([to5(r["gt6"]) for r in per_seed[s]], pr)
            per.append({"seed": s, "macro_f1": m["macro"]["f1"],
                        "recall": {c: m["per_class"][c]["recall"] for c in CLASSES}})
        v = [t["macro_f1"] for t in per]
        abl[g] = {"removed": cols, "per_seed": per, "mean": sum(v) / len(v), "sd_sample_ddof1": sd(v, 1),
                  "mean_recall": {c: sum(t["recall"][c] for t in per) / len(per) for c in CLASSES}}
    res["ablation_J48"] = abl

    if VARIANT == "v2":
        res["v2_extra"] = v2_extra(per_seed, outdir, allf, sd)

    # 6. self-checks (sanity values required by the revision prompt)
    assert res["path_check"]["b0_rerun_equals_recorded"] == 100
    assert res["path_check"]["b1_rerun_equals_recorded"] == 100
    assert res["path_check"]["mapping_equals_category"] == 100
    assert all(v == 20 for v in res["supports"].values())
    if VARIANT == "v2":
        assert max(r["shock_mag_g"] for t in per_seed.values() for r in t) <= 16.0
