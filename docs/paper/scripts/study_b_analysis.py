def run_detectors(rows):
    """Re-run the frozen B0/B1 code on the recorded observations, as runner.py does (one B1 instance)."""
    b0, b1 = BaselineDetectorB0(), ProposedDetectorB1()
    out = []
    for r in rows:
        blocked = r["credential"] in BLOCKED
        v0 = b0.evaluate(auth_result=r["auth_result"], door_open_sec=r["door_open_sec"],
                         weight_delta_g=r["weight_delta_g"], rfid_ok=r["rfid_ok"],
                         stay_min=r["stay_min"], card_blocked=blocked)
        stream = [{"seq": r["seq"]}, {"seq": r["seq"]}] if r["seq_replay"] else None
        v1 = b1.evaluate(auth_result=r["auth_result"], door_open_sec=r["door_open_sec"],
                         weight_delta_g=r["weight_delta_g"], rfid_ok=r["rfid_ok"], stay_min=r["stay_min"],
                         ultrasonic_dist_cm=r["ultrasonic_dist_cm"], vibration_intensity=r["vibration_intensity"],
                         tilt_deg=r["tilt_deg"], shock_mag_g=r["shock_mag_g"], card_blocked=blocked,
                         network_latency_ms=r["network_latency_ms"], packet_seq=None, telemetry_records=stream)
        out.append((v0.label, v1.label))
    return out


