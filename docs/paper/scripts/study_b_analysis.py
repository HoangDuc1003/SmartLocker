def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def to5(label):
    return CANONICAL_TO_EVALUATION_MAP[label]


# ----------------------------------------------------------------------------- metrics
def confusion(y, p):
    cm = {a: {b: 0 for b in CLASSES} for a in CLASSES}
    for a, b in zip(y, p):
        cm[a][b] += 1
    return cm


def metrics(y, p):
    cm = confusion(y, p)
    n = len(y)
    per = {}
    for c in CLASSES:
        tp = cm[c][c]
        sup = sum(cm[c].values())
        pp = sum(cm[a][c] for a in CLASSES)
        pr = tp / pp if pp else 0.0
        rc = tp / sup if sup else 0.0
        f1 = 2 * pr * rc / (pr + rc) if pr + rc else 0.0
        per[c] = {"precision": pr, "recall": rc, "f1": f1, "support": sup, "predicted": pp}
    sup = {c: per[c]["support"] for c in CLASSES}
    mac = {k: sum(per[c][k] for c in CLASSES) / len(CLASSES) for k in ("precision", "recall", "f1")}
    wtd = {k: sum(per[c][k] * sup[c] for c in CLASSES) / n for k in ("precision", "recall", "f1")}
    acc = sum(cm[c][c] for c in CLASSES) / n
    # binary: Anomaly (anything but NORMAL_AUTHORIZED) is the positive class
    ya = [a != CLASSES[0] for a in y]
    pa = [b != CLASSES[0] for b in p]
    tp = sum(1 for a, b in zip(ya, pa) if a and b)
    fp = sum(1 for a, b in zip(ya, pa) if not a and b)
    fn = sum(1 for a, b in zip(ya, pa) if a and not b)
    bpr = tp / (tp + fp) if tp + fp else 0.0
    brc = tp / (tp + fn) if tp + fn else 0.0
    return {
        "confusion": cm, "per_class": per, "accuracy": acc,
        "balanced_accuracy": mac["recall"], "macro": mac, "weighted": wtd,
        "binary_anomaly_positive": {
            "accuracy": sum(1 for a, b in zip(ya, pa) if a == b) / n,
            "precision": bpr, "recall": brc,
            "f1": 2 * bpr * brc / (bpr + brc) if bpr + brc else 0.0,
            "tp": tp, "fp": fp, "fn": fn, "tn": n - tp - fp - fn},
    }


def macro_f1(y, p):
    return metrics(y, p)["macro"]["f1"]


def mcnemar(y, p0, p1, binary):
    """n01 = B0 wrong & B1 right, n10 = B0 right & B1 wrong."""
    def ok(a, b):
        return (a != CLASSES[0]) == (b != CLASSES[0]) if binary else a == b
    n = {"n00": 0, "n01": 0, "n10": 0, "n11": 0}
    for a, b0, b1 in zip(y, p0, p1):
        n["n%d%d" % (ok(a, b0), ok(a, b1))] += 1
    d = n["n01"] + n["n10"]
    chi2 = (abs(n["n01"] - n["n10"]) - 1) ** 2 / d if d else 0.0
    k = min(n["n01"], n["n10"])
    p_exact = min(1.0, 2 * sum(math.comb(d, i) for i in range(k + 1)) / 2 ** d) if d else 1.0
    return dict(n, chi2_cc=chi2, exact_binomial_p_two_sided=p_exact)


